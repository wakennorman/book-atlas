/* 简→繁转换的**人工覆盖表** —— v0.219 新增。
 *
 * ## 为什么需要它
 *
 * 生成器以 opencc-js（MIT）为基准产出字表与词组表，但 opencc 的判据来自**通用语料**，
 * 放到本书的文学散文与专名上会翻车。实测（v0.219：语料 = 六本书的读者可见字段 + UI 文案，
 * 266,682 字 / 3,523 个去重汉字 / 98 个多义字 / 803 条需要人工判的规则）分三类：
 *
 * ① **默认形式取错**（`CHAR_FIX`）—— 逐字转换给出的是罕见那一支。
 *    `才→纔`、`了→瞭`、`布→佈`、`制→製`、`钟→鍾`、`里→裏` ……
 * ② **词组判错 / 同 bigram 两个答案**（`PHRASE_FIX`）—— 宣布→宣佈、了解→瞭解、
 *    丰度→丰度、复述→複述、复盘→覆盤、干草→干草 ……
 * ③ **音译名被词组层误伤**（`PROTECT_PHRASES`）—— 「奥雷里」被判成「奧雷裡」、
 *    「托夫」判成「託夫」、「赫里内勒」判成「赫裡內勒」。
 *
 * ## 默认形式不是拍脑袋定的
 *
 * `CHAR_FIX` **只列实测翻车的字**；其余每个字的默认形由生成器统计
 * 「本语料里 opencc 在真实上下文中实际给出它的哪一支、哪一支最多」自动得出。
 * ⚠ 首版把「看起来该转」当理由往 `CHAR_FIX` 里加，结果砸了：
 * 「赵云→趙云」「阿斗→阿鬥」「皇后→皇後」「世系→世係」——
 * 把默认改成原形，会让**正确**的那一支变成"少数派"而丢掉词组规则。
 * **原则：默认取多数派，少数派由 `PHRASE_FIX` 钉死；只有多数派本身就错时才动 `CHAR_FIX`。**
 *
 * ## 覆盖表要被守卫反向锁住
 *
 * `test/s2t-guard.mjs` 的 S2/S3：本语料里凡与本表不一致的位置，
 * 都必须有**明确条目**，不许靠默认值蒙对。
 *
 * 本表**纯数据、无副作用**。
 */

