/**
 * 根据译名差异表，生成所有变体
 * @param {string} name - 基础名字
 * @returns {string[]} 所有变体（包括原名）
 */
export function variantsOf(name) {
  const set = new Set([name]);
  for (const [a, b] of VARIANT_PAIRS) {
    if (name.includes(a)) set.add(name.replace(a, b));
    if (name.includes(b)) set.add(name.replace(b, a));
  }
  return [...set];
}
